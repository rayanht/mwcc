void CTemplateNew_InitAsmOperandPatternLookup(void)
{
    int i;
    AsmOperandPattern *entry;
    NameLookupLink *node;
    NameLookupLink **bucket;
    short hash;

    for (i = 0; i < 256L; i += 8) {
        asmOperandPatternLookup[i] = NULL;
        asmOperandPatternLookup[i + 1] = NULL;
        asmOperandPatternLookup[i + 2] = NULL;
        asmOperandPatternLookup[i + 3] = NULL;
        asmOperandPatternLookup[i + 4] = NULL;
        asmOperandPatternLookup[i + 5] = NULL;
        asmOperandPatternLookup[i + 6] = NULL;
        asmOperandPatternLookup[i + 7] = NULL;
    }
    for (entry = asm_operand_patterns; entry->name != NULL; ++entry) {
        hash = CHash(entry->name);
        bucket = asmOperandPatternLookup + (hash & 0xff);
        node = lalloc(sizeof(*node));
        node->record = entry;
        node->next = *bucket;
        *bucket = node;
    }
}

AsmOperandPattern *CTemplateNew_FindAsmOperandPattern(char *name)
{
    NameLookupLink *link;
    AsmOperandPattern *record;
    int comparison;

    link = asmOperandPatternLookup[CHash(name) & 0xff];
    while (link != NULL) {
        record = link->record;
        comparison = strcmp((char *)record->name, name);
        if (comparison == 0) {
            return record;
        }
        link = link->next;
    }
    return NULL;
}
